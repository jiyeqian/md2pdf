#!/usr/bin/env node
// Fixed-version parser bundle; npm is only needed by maintainers rebuilding it.
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const exec = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'vendor', 'yaml');
const versions = { yaml: '2.8.1', esbuild: '0.25.4' };
const temporary = await mkdtemp(path.join(os.tmpdir(), 'md2pdf-yaml-build-'));
try {
  await writeFile(path.join(temporary, 'package.json'), JSON.stringify({ private: true, type: 'module', dependencies: versions }));
  await exec('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: temporary });
  await writeFile(path.join(temporary, 'entry.mjs'), "export { parseDocument, isMap, isSeq } from 'yaml';\n");
  await mkdir(target, { recursive: true });
  await exec(path.join(temporary, 'node_modules', '.bin', 'esbuild'), [
    'entry.mjs', '--bundle', '--platform=node', '--format=esm', '--target=node18',
    '--minify', '--legal-comments=none', '--outfile=' + path.join(target, 'yaml.mjs'),
    '--banner:js=// yaml 2.8.1 (ISC); generated by scripts/build-yaml.mjs; see LICENSE and provenance.json.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
  ], { cwd: temporary });
  const source = path.join(temporary, 'node_modules', 'yaml');
  await writeFile(path.join(target, 'LICENSE'), await readFile(path.join(source, 'LICENSE')));
  const pkg = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
  const bundle = await readFile(path.join(target, 'yaml.mjs'));
  await writeFile(path.join(target, 'provenance.json'), JSON.stringify({
    package: pkg.name, version: pkg.version, license: pkg.license,
    repository: pkg.repository, buildTool: 'esbuild', buildToolVersion: versions.esbuild,
    exports: ['parseDocument', 'isMap', 'isSeq'], sha256: createHash('sha256').update(bundle).digest('hex'),
  }, null, 2) + '\n');
  console.log(`Built vendor/yaml/yaml.mjs (${bundle.length} bytes)`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
